/** Textos con partes variables (nombre, número). */
const PATRONES: [RegExp, string][] = [
  [/^Pregunta (\d+)$/, "Question $1"],
  [/^Opción (\d+)$/, "Option $1"],
  [/^Hola, (.*)$/, "Hello, $1"],
  [/^Asignar: (.*)$/, "Assign: $1"],
  [/^Matricular en: (.*)$/, "Enroll in: $1"],
  [/^Nota: (.*) \/ 100$/, "Grade: $1 / 100"],
  [/^Respuestas correctas: (.*) de (.*)$/, "Correct answers: $1 of $2"],
  [/^Tiempo usado: (.*)$/, "Time used: $1"],
  [/^(\d+)\. (.*)$/, "$1. $2"],
];

export function traducir(texto: string, idioma: Idioma): string {
  if (idioma === "es") return texto;
  const exacto = EN[texto];
  if (exacto !== undefined) return exacto;
  for (const [patron, reemplazo] of PATRONES) {
    if (patron.test(texto)) return texto.replace(patron, reemplazo);
  }
  return texto;
}
